from abc import ABC, abstractmethod
from ..schemas import Location

class WeatherProvider(ABC):
    @abstractmethod
    async def geocode(self, query: str) -> Location: ...
    @abstractmethod
    async def current(self, location: Location) -> dict: ...
    @abstractmethod
    async def forecast(self, location: Location) -> dict: ...
    @abstractmethod
    async def historical(self, location: Location) -> dict: ...
